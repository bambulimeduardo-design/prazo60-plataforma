-- 2. Base interna (nivel caso). NAO e liberada para o usuario do site.
CREATE OR REPLACE VIEW ADMIN.VW_P60_BASE AS
SELECT c.ID_CASO,
       EXTRACT(YEAR FROM c.DATA_DIAGNOSTICO)  AS ANO,
       EXTRACT(MONTH FROM c.DATA_DIAGNOSTICO) AS MES,
       t.DIAS_ESPERA,
       CASE WHEN t.DIAS_ESPERA > 60 THEN 1 ELSE 0 END AS ACIMA_60,
       d.COD_DRS, d.NOME_DRS, m.NOME_MUNICIPIO,
       u.COD_CNES, u.NOME_UNIDADE,
       mu.NOME_MUNICIPIO AS MUNICIPIO_UNIDADE, du.COD_DRS AS COD_DRS_UNIDADE, du.NOME_DRS AS DRS_UNIDADE,
       tt.NOME_TIPO_TRATAMENTO
FROM ADMIN.TB_CASO_PACIENTE c
JOIN ADMIN.TB_TRATAMENTO t       ON t.ID_CASO = c.ID_CASO
JOIN ADMIN.TB_MUNICIPIO m        ON m.ID_MUNICIPIO = c.ID_MUNICIPIO_RESIDENCIA
JOIN ADMIN.TB_DRS d              ON d.ID_DRS = m.ID_DRS
JOIN ADMIN.TB_UNIDADE_SAUDE u    ON u.ID_UNIDADE = t.ID_UNIDADE_TRATAMENTO
JOIN ADMIN.TB_MUNICIPIO mu       ON mu.ID_MUNICIPIO = u.ID_MUNICIPIO
JOIN ADMIN.TB_DRS du             ON du.ID_DRS = mu.ID_DRS
JOIN ADMIN.TB_TIPO_TRATAMENTO tt ON tt.ID_TIPO_TRATAMENTO = t.ID_TIPO_TRATAMENTO;

-- 3. Views agregadas para a IA
CREATE OR REPLACE VIEW ADMIN.VW_P60_RESUMO_ANO AS
SELECT ANO,
       CASE WHEN ANO = (SELECT MAX(ANO) FROM ADMIN.VW_P60_BASE) THEN 'SIM' ELSE 'NAO' END AS ANO_PARCIAL,
       COUNT(*) AS CASOS,
       SUM(ACIMA_60) AS CASOS_ACIMA_60,
       ROUND(100 * AVG(ACIMA_60), 1) AS PCT_ACIMA_60,
       ROUND(AVG(DIAS_ESPERA), 1) AS MEDIA_DIAS,
       MEDIAN(DIAS_ESPERA) AS MEDIANA_DIAS
FROM ADMIN.VW_P60_BASE
GROUP BY ANO;

CREATE OR REPLACE VIEW ADMIN.VW_P60_RESUMO_MES AS
SELECT ANO, MES, TO_CHAR(ANO) || '-' || LPAD(MES, 2, '0') AS ANO_MES,
       COUNT(*) AS CASOS,
       SUM(ACIMA_60) AS CASOS_ACIMA_60,
       ROUND(100 * AVG(ACIMA_60), 1) AS PCT_ACIMA_60,
       ROUND(AVG(DIAS_ESPERA), 1) AS MEDIA_DIAS,
       MEDIAN(DIAS_ESPERA) AS MEDIANA_DIAS
FROM ADMIN.VW_P60_BASE
GROUP BY ANO, MES;

CREATE OR REPLACE VIEW ADMIN.VW_P60_DRS_ANO AS
SELECT COD_DRS, NOME_DRS, ANO,
       COUNT(*) AS CASOS,
       SUM(ACIMA_60) AS CASOS_ACIMA_60,
       ROUND(100 * AVG(ACIMA_60), 1) AS PCT_ACIMA_60,
       ROUND(AVG(DIAS_ESPERA), 1) AS MEDIA_DIAS,
       MEDIAN(DIAS_ESPERA) AS MEDIANA_DIAS
FROM ADMIN.VW_P60_BASE
GROUP BY COD_DRS, NOME_DRS, ANO;

CREATE OR REPLACE VIEW ADMIN.VW_P60_DRS AS
SELECT b.COD_DRS, b.NOME_DRS,
       COUNT(*) AS CASOS,
       SUM(b.ACIMA_60) AS CASOS_ACIMA_60,
       ROUND(100 * AVG(b.ACIMA_60), 1) AS PCT_ACIMA_60,
       ROUND(AVG(b.DIAS_ESPERA), 1) AS MEDIA_DIAS,
       MEDIAN(b.DIAS_ESPERA) AS MEDIANA_DIAS,
       ROUND(100 * AVG(CASE WHEN b.ANO = 2024 THEN b.ACIMA_60 END), 1) AS PCT_ACIMA_60_2024,
       ROUND(100 * AVG(CASE WHEN b.ANO = 2025 THEN b.ACIMA_60 END), 1) AS PCT_ACIMA_60_2025,
       ROUND(100 * AVG(CASE WHEN b.ANO = 2025 THEN b.ACIMA_60 END), 1)
         - ROUND(100 * AVG(CASE WHEN b.ANO = 2024 THEN b.ACIMA_60 END), 1) AS VARIACAO_PP_2024_2025,
       SUM(CASE WHEN b.ANO = 2025 THEN 1 ELSE 0 END) AS CASOS_2025,
       MAX(o.ESTABELECIMENTOS_CACON_UNACON) AS ESTABELECIMENTOS_2025,
       MAX(o.MAMOGRAFIAS_RASTREIO) AS MAMOGRAFIAS_2025,
       ROUND(SUM(CASE WHEN b.ANO = 2025 THEN 1 ELSE 0 END) / NULLIF(MAX(o.ESTABELECIMENTOS_CACON_UNACON), 0), 1) AS PRESSAO_CASOS_POR_ESTABELECIMENTO
FROM ADMIN.VW_P60_BASE b
LEFT JOIN ADMIN.TB_OFERTA_DRS o ON o.COD_DRS = b.COD_DRS AND o.ANO = 2025
GROUP BY b.COD_DRS, b.NOME_DRS;

CREATE OR REPLACE VIEW ADMIN.VW_P60_MUNICIPIO AS
SELECT NOME_MUNICIPIO, COD_DRS, NOME_DRS,
       COUNT(*) AS CASOS,
       SUM(ACIMA_60) AS CASOS_ACIMA_60,
       ROUND(100 * AVG(ACIMA_60), 1) AS PCT_ACIMA_60,
       ROUND(AVG(DIAS_ESPERA), 1) AS MEDIA_DIAS,
       MEDIAN(DIAS_ESPERA) AS MEDIANA_DIAS
FROM ADMIN.VW_P60_BASE
WHERE NOME_MUNICIPIO <> 'Fora do Estado de SP'
GROUP BY NOME_MUNICIPIO, COD_DRS, NOME_DRS
HAVING COUNT(*) >= 30;

CREATE OR REPLACE VIEW ADMIN.VW_P60_UNIDADE AS
SELECT COD_CNES, NOME_UNIDADE, MUNICIPIO_UNIDADE AS NOME_MUNICIPIO, COD_DRS_UNIDADE AS COD_DRS, DRS_UNIDADE AS NOME_DRS,
       COUNT(*) AS CASOS,
       SUM(ACIMA_60) AS CASOS_ACIMA_60,
       ROUND(100 * AVG(ACIMA_60), 1) AS PCT_ACIMA_60,
       ROUND(AVG(DIAS_ESPERA), 1) AS MEDIA_DIAS,
       MEDIAN(DIAS_ESPERA) AS MEDIANA_DIAS
FROM ADMIN.VW_P60_BASE
GROUP BY COD_CNES, NOME_UNIDADE, MUNICIPIO_UNIDADE, COD_DRS_UNIDADE, DRS_UNIDADE
HAVING COUNT(*) >= 30;

CREATE OR REPLACE VIEW ADMIN.VW_P60_TIPO_TRATAMENTO AS
SELECT NOME_TIPO_TRATAMENTO AS TIPO_TRATAMENTO,
       COUNT(*) AS CASOS,
       SUM(ACIMA_60) AS CASOS_ACIMA_60,
       ROUND(100 * AVG(ACIMA_60), 1) AS PCT_ACIMA_60,
       ROUND(AVG(DIAS_ESPERA), 1) AS MEDIA_DIAS,
       MEDIAN(DIAS_ESPERA) AS MEDIANA_DIAS
FROM ADMIN.VW_P60_BASE
GROUP BY NOME_TIPO_TRATAMENTO;

CREATE OR REPLACE VIEW ADMIN.VW_P60_FAIXA_DIAS AS
SELECT FAIXA, ORDEM, COUNT(*) AS CASOS, ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 1) AS PCT_DO_TOTAL
FROM (SELECT CASE WHEN DIAS_ESPERA <= 30 THEN '0-30' WHEN DIAS_ESPERA <= 45 THEN '31-45'
                  WHEN DIAS_ESPERA <= 60 THEN '46-60' WHEN DIAS_ESPERA <= 90 THEN '61-90'
                  WHEN DIAS_ESPERA <= 120 THEN '91-120' ELSE '121+' END AS FAIXA,
             CASE WHEN DIAS_ESPERA <= 30 THEN 1 WHEN DIAS_ESPERA <= 45 THEN 2 WHEN DIAS_ESPERA <= 60 THEN 3
                  WHEN DIAS_ESPERA <= 90 THEN 4 WHEN DIAS_ESPERA <= 120 THEN 5 ELSE 6 END AS ORDEM
      FROM ADMIN.VW_P60_BASE)
GROUP BY FAIXA, ORDEM;

