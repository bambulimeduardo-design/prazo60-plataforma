-- 5. Usuario do site: libera as views agregadas e retira o acesso as tabelas de nivel caso
BEGIN
  FOR v IN (SELECT column_value AS nome FROM TABLE(SYS.ODCIVARCHAR2LIST(
              'VW_P60_RESUMO_ANO', 'VW_P60_RESUMO_MES', 'VW_P60_DRS', 'VW_P60_DRS_ANO',
              'VW_P60_MUNICIPIO', 'VW_P60_UNIDADE', 'VW_P60_TIPO_TRATAMENTO', 'VW_P60_FAIXA_DIAS'))) LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON ADMIN.' || v.nome || ' TO PRAZO60_APP';
  END LOOP;
  FOR t IN (SELECT column_value AS nome FROM TABLE(SYS.ODCIVARCHAR2LIST(
              'VW_CASO_PACIENTE', 'TB_TRATAMENTO', 'TB_UNIDADE_SAUDE', 'TB_MUNICIPIO',
              'TB_DRS', 'TB_STATUS_PRAZO', 'TB_TIPO_TRATAMENTO'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'REVOKE SELECT ON ADMIN.' || t.nome || ' FROM PRAZO60_APP';
    EXCEPTION WHEN OTHERS THEN NULL;
    END;
  END LOOP;
END;
